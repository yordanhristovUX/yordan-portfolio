function mediaBySlot(project, slot) {
  const m = (project.media ?? []).find((x) => x.slot === slot);
  if (!m) throw new Error(`${project._file}: no media slot "${slot}"`);
  return m;
}

const phFigure = (m) =>
  `<figure class="ph"><span class="ph__label">${inline(m.caption)}</span></figure>`;

