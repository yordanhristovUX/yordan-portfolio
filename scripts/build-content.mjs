function svgFigure(m) {
  const svg = readFileSync(join(root, "content", "assets", m.src), "utf8");
  return [
    `<figure style="border: 1px solid var(--chrome-border-strong); background: var(--surface-raised); padding: 1.25rem; margin: 1.5rem 0; color: var(--content-primary); max-width: none;">`,
    ...indent(2, lf(svg).trimEnd().split("\n")),
    `  <figcaption class="mono" style="font-size:.68rem;letter-spacing:.08em;text-transform:uppercase;color:var(--chrome-label);margin-top:.75rem">${inline(
      m.caption
    )}</figcaption>`,
    `</figure>`,
  ];
}

function renderDirective(project, value) {
  const [name, arg] = value.split(":");
  if (name === "metric") {
    const metric = project.metrics?.[Number(arg)];
    if (!metric) throw new Error(`${project._file}: {{metric:${arg}}} has no matching metrics entry`);
    return { lines: [`<p><span class="stat">${inline(metric.value)}</span></p>`] };
  }
  if (name === "media") return { lines: mediaLines(project, arg) };
  if (name === "media-grid") {
    return {
      blankBefore: true,
      lines: [
        `<div class="ph-grid">`,
        ...indent(2, arg.split(",").map((s) => phFigure(mediaBySlot(project, s.trim())))),
        `</div>`,
      ],
    };
  }
  if (name === "links") return { lines: linkLines(project.links ?? []) };
  throw new Error(`${project._file}: unknown directive {{${value}}}`);
}

function mediaLines(project, slot) {
  const m = mediaBySlot(project, slot);
  return m.type === "svg" ? svgFigure(m) : [phFigure(m)];
}

/* One link renders bare; two or more sit in a <p> with the leading ones spaced. */
function linkLines(links) {
  if (!links.length) return [];
  if (links.length === 1) return [anchor({ ...links[0], btn: true })];
  return [
    `<p>`,
    ...indent(
      2,
      links.map((l, i) =>
        anchor({ ...l, btn: true, style: i < links.length - 1 ? "margin-right:.6rem" : undefined })
      )
    ),
    `</p>`,
  ];
}

function renderCaseContent(project) {
  const out = [];
  const push = (blankBefore, lines) => {
    if (blankBefore && out.length) out.push("");
    out.push(...lines);
  };

  const cover = (project.media ?? []).find((m) => m.slot === "cover");
  if (cover) push(false, [phFigure(cover)]);

  for (const s of project.sections) {
    if (s.kind === "summary" || s.kind === "subtitle") continue;
    push(true, [`<h3>${inline(s.heading)}</h3>`]);
    for (const b of s.blocks) {
      if (b.type === "p") push(false, [`<p>${inline(b.text)}</p>`]);
      else if (b.type === "list") {
        push(false, [`<ul>`, ...indent(2, b.items.map((i) => `<li>${inline(i)}</li>`)), `</ul>`]);
      } else {
        const d = renderDirective(project, b.value);
        push(Boolean(d.blankBefore), d.lines);
      }
    }
  }
  return out;
}

