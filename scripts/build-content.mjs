/* `.entry__span` is FORMATTED from {start, end, note, location, mode} — never
   authored. "Jan 2026 – Present · Sofia · Hybrid" is a rendering of a date. */
const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
function formatDate(v) {
  if (!v) return "Present";
  const m = String(v).match(/^(\d{4})(?:-(\d{2}))?$/);
  if (!m) throw new Error(`unparseable date "${v}" — use "YYYY" or "YYYY-MM"`);
  return m[2] ? `${MONTHS[Number(m[2]) - 1]} ${m[1]}` : m[1];
}
function formatPeriod(p) {
  const span = `${formatDate(p.start)} – ${formatDate(p.end)}`;
  return [span, p.note, p.location, p.mode].filter(Boolean).join(" · ");
}

