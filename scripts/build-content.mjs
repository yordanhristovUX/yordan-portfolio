/* ============================================================
   6. content/dist/content.json — the retrieval index

   One chunk per section, plus precomputed BM25 term frequencies and corpus
   statistics. Deterministic by construction: no timestamps, stable ordering,
   so `--check` compares bytes and means it.
   ============================================================ */
/* Punctuation is trimmed from the ENDS of a token and never from the middle.
   A blanket split would be wrong in both directions here: leaving sentence
   punctuation on made `analytics` and `analytics.` two different terms, which
   halves IDF for both and silently loses every chunk where the word happened to
   end a sentence; but stripping punctuation everywhere would destroy tokens this
   corpus actually means — `200+`, `−40%`, `1:1`, `2.1`, `64×80`, `5–6`, `p5.js`,
   `tokens.json`, `build.mjs`, `case-studies.js`, `spec.md`. */
const EDGE_PUNCT = /^[.,;:!?"'’“”()[\]—–…·]+|[.,;:!?"'’“”()[\]—–…·]+$/g;

const tokenize = (s) =>
  s
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .split(/[\s/·|]+/)
    .flatMap((raw) => {
      // Possessives are the same defect as trailing full stops: `wcag` and
      // `wcag's` are one term, not two.
      const t = raw.replace(EDGE_PUNCT, "").replace(/['’]s$/, "");
      // Word compounds keep splitting on the hyphen exactly as they always have
      // (`ai-ready` → ai, ready), so this change is the punctuation fix and
      // nothing else. Anything carrying a dot or a digit is an identifier or a
      // measurement and stays whole.
      return t.includes("-") && !/[.\d]/.test(t) ? t.split("-") : [t];
    })
    .filter((t) => t.length > 1 && t.length < 32);

const chunks = [];
/* Section kinds repeat within a single entity — the audit carries two
   {#approach} and two {#outcome} — so `entity#kind` is not unique on its own.
   Six of seventy-six ids collided before this. An ambiguous id makes a citation
   point at a section KIND rather than a passage, and passage-level precision is
   exactly what the provenance gate in lib/knowledge/schema.js exists to check;
   a citation that can mean two paragraphs cannot prove either one.

   Later collisions take an ordinal. The first keeps the bare id so the common
   single-section case stays readable — note this means inserting a new section
   ahead of an existing one of the same kind moves the bare id to the newcomer.
   That is acceptable because citations are validated against the current index
   on every request, never stored, so they are never stale in a way that matters. */
const seenChunkIds = new Set();

function addChunk(id, entity, kind, heading, text, cite) {
  /* elideStats BEFORE plain(): see the note beside it. Both fields are elided
     because build-vectors hashes `${heading}. ${text}` — a statistic in a
     heading would couple the cache just as tightly as one in the body. */
  const t = plain(elideStats(text));
  if (!t) return;
  let unique = id;
  for (let n = 2; seenChunkIds.has(unique); n++) unique = `${id}-${n}`;
  seenChunkIds.add(unique);
  chunks.push({ id: unique, entity, kind, heading: elideStats(heading), text: t, cite });
}

