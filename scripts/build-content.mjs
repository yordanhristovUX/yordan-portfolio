const jsString = (s) => JSON.stringify(s);
const jsKey = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));
const jsTemplate = (s) => s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");

function buildCaseStudiesJs() {
  const out = [
    `/* GENERATED by scripts/build-content.mjs from content/ — do not edit.`,
    `   Edit content/projects/*.md and run \`node scripts/build-content.mjs\`.`,
    `   Case study content — condensed from the full Notion case studies. */`,
    `window.CASE_STUDIES = {`,
  ];
  caseStudies.forEach((p, i) => {
    const body = renderCaseContent(p);
    out.push(`  ${jsKey(p.id)}: {`);
    out.push(`    index: ${jsString(`${String(p.index).padStart(2, "0")} / ${p.client}`)},`);
    out.push(`    title: ${jsString(p.title)},`);
    out.push(`    subtitle:`);
    out.push(`      ${jsString(sectionText(p, "subtitle"))},`);
    out.push(`    meta: [${p.tags.map(jsString).join(", ")}],`);
    out.push(`    accentMeta: [${jsString(p.accentTag)}],`);
    out.push(`    content: \``);
    out.push(...indent(6, body).map(jsTemplate));
    out.push(`    \`,`);
    out.push(`  },${i < caseStudies.length - 1 ? "\n" : ""}`);
  });
  out.push(`};`);
  return out.join("\n") + "\n";
}

/* ============================================================
   5. Page regions

   The generator owns the inner HTML of each `<!-- content:NAME -->` region and
   nothing else: the skeleton, the section structure and the data-reveal /
   data-rise / data-lines hooks stay in the page where they belong.

   `data-count` used to be in that list. It is not emitted anywhere any more —
   see the note above factCell.
   ============================================================ */
function applyRegions(html, regions, file) {
  let out = lf(html);
  for (const [name, lines] of Object.entries(regions)) {
    const open = `<!-- content:${name} -->`;
    const close = `<!-- /content:${name} -->`;
    const start = out.indexOf(open);
    const end = out.indexOf(close, start);
    if (start === -1 || end === -1) {
      console.error(
        `✗ ${file}: region marker ${open} … ${close} not found.\n` +
          `  Generated regions are delimited in the page; the skeleton around them is hand-authored.`
      );
      process.exit(1);
    }
    /* Re-indent to whatever depth the opening marker sits at, so a region can be
       moved in the page without the generator caring. */
    const lineStart = out.lastIndexOf("\n", start) + 1;
    const at = out.slice(lineStart, start).length;
    const closeLineStart = out.lastIndexOf("\n", end) + 1;
    out =
      out.slice(0, start + open.length) +
      "\n" +
      indent(at, lines).join("\n") +
      (lines.length ? "\n" : "") +
      out.slice(closeLineStart);
  }
  return out;
}

