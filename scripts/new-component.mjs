#!/usr/bin/env node
/* ============================================================
   Component scaffold — zero dependencies.

   `npm run new:component -- <id> [--title "Nice name"] [--dry-run] [--json]`

   WHAT THIS IS FOR. design-system/README.md states the contract — a
   component is a CSS block AND a spec.md AND a story — and
   design-system/scripts/build.mjs enforces it three ways: coverage
   (all three files exist), the `@component` markers (every CSS block
   is owned, every component owns a block), and the contract gate
   (frontmatter is valid, every class the spec claims has a rule, and
   the `## Tokens` list is exactly the set of `var(--…)` the block
   consumes). That is a good contract and none of it is being relaxed
   here. It is simply cheaper to START satisfied than to discover the
   five requirements one error message at a time.

   Everything this emits is derived from the gates themselves — the
   banner shape from build.mjs's BANNER regex, the frontmatter keys
   and their allowed values from its STATUSES/PHASES lists, the token
   list from its consumed-vs-declared cross-check. If a gate changes,
   this scaffold should be changed with it; the failure mode is a loud
   one, because the next `npm run check` says exactly what is wrong.

   THE TRINITY IS A QUARTET, AND THE CENSUS IS WHY IT HAD TO BECOME
   ONE. R4 gave css/components.css a census: every block is either
   inside a `generated:<id>` region or carries
   `/* ---- authored:<id> — <reason> ---- ` from a closed vocabulary,
   and the build refuses a reason its scan cannot find in the block. A
   freshly scaffolded block has one class and one declaration — it has
   no combinator, no local custom property, no unnamed condition and no
   foreign selector, so there is NO honest authored reason available to
   it. The census therefore does not merely permit a scaffold to emit a
   definition; it makes that the only truthful thing to emit. A new
   component is generated by default, and it is authored only once it
   has earned a reason.

   So this writes FOUR artefacts and THREE registrations: the
   definition, the spec, the story and the generated region, plus the
   id in `PILOT`, the `dist/react/<id>.tsx` line in build.mjs's
   `packaged` array, and the `./react/<id>` subpath in the package's
   `exports` map. All three are mechanical lists, and each stays one
   literal line in a diff — `packaged`'s own banner asks for exactly
   that, because test/drift.test.js parses it as source.

   WHAT IT DELIBERATELY DOES NOT DO: touch the two hand-written
   READMEs, the `//exports` sentence that counts the subpaths, or the
   version. Adding a component moves a number the site advertises about
   itself, and build.mjs asserts that number in four files. Two of them
   are generated (`npm run build` fixes those). Two are prose a person
   wrote, and a scaffold that silently rewrites the sentences making a
   claim about the system is how a gate stops being trusted. The
   version is the same kind of claim, and contract-diff.mjs --release
   is where a person makes it. So it prints them instead. See the
   report at the end.
   ============================================================ */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/* ---------- how this reaches the emitter, and why not by importing it ----------
   The obvious move is `import { renderBlock } from "../design-system/scripts/emit-css.mjs"`,
   so the region this writes is byte-identical to what build.mjs will re-render.
   scripts/check-boundaries.mjs refuses it, and it is right to: the design system
   publishes dist/ and css/, and `scripts/` is private to it — a root tool
   reaching in is the crossing this repo's whole architecture is organised
   against, and it would be reaching in for a FUNCTION rather than an artefact.

   So this writes the region EMPTY — the two markers and nothing between them —
   and then RUNS the emitter as a process, exactly as package.json's own `build`
   script does. Spawning a slice's entry point is not a boundary crossing; it is
   how every other consumer of that slice already works. The body therefore comes
   out of emit-css.mjs on the first run rather than being imitated here, and the
   only thing restated is the marker text itself, which is a two-line format that
   ../design-system/README.md and PATTERNS.md already spell out in prose. If it
   ever drifts, `regionOf` fails to find the region and says so by name. */
const openMarker = (id) => `/* ---- generated:${id} — do not edit, source: components/${id}/definition.json ---- */`;
const closeMarker = (id) => `/* ---- /generated:${id} ---- */`;

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ds = join(root, "design-system");

/* ---------- argv ---------- */
const argv = process.argv.slice(2);
const VALUE_FLAGS = new Set(["--title"]);
const flag = (name) => argv.includes(name);
const opt = (name) => {
  const i = argv.indexOf(name);
  return i === -1 ? null : argv[i + 1];
};
const DRY = flag("--dry-run");
const JSON_OUT = flag("--json");
const id = argv.find((a, i) => !a.startsWith("--") && !VALUE_FLAGS.has(argv[i - 1]));

const die = (msg) => {
  console.error(`✗ ${msg}`);
  process.exit(1);
};

if (!id) {
  die(
    `usage: npm run new:component -- <id> [--title "Nice name"] [--dry-run]\n` +
      `  <id> is the directory name, the story file name and the base class: e.g. \`link-grid\` → \`.link-grid\`.`
  );
}
/* The id is a directory name, a file name AND a CSS class, so it has to be
   legal as all three. kebab-case is the house convention (`section-head`,
   `theme-toggle`, `link-grid`) and build.mjs's suffix parser reads `--` as a
   variant separator, so a doubled dash in the id itself would misparse. */
if (!/^[a-z][a-z0-9]*(-[a-z0-9]+)*$/.test(id)) {
  die(`"${id}" is not a valid component id — lower-case, kebab-case, no leading digit, no doubled dash (e.g. link-grid).`);
}

const title = opt("--title") ?? id.replace(/-/g, " ").replace(/^./, (c) => c.toUpperCase());

/* ---------- refuse to collide ---------- */
const compDir = join(ds, "components", id);
const storyPath = join(ds, "stories", `${id}.stories.js`);
const cssPath = join(ds, "css", "components.css");
const css = readFileSync(cssPath, "utf8");

if (existsSync(compDir)) die(`design-system/components/${id}/ already exists.`);
if (existsSync(storyPath)) die(`design-system/stories/${id}.stories.js already exists.`);
if (new RegExp(`@component ${id}\\b`).test(css)) die(`css/components.css already has a block marked \`@component ${id}\`.`);
/* A class that already has a rule somewhere else would make the spec's claim
   true by accident and put two owners on one selector. */
if (new RegExp(`\\.${id}(?![\\w-])`).test(css)) {
  die(`css/components.css already defines \`.${id}\` — pick another id, or the new block and the old one will fight over it.`);
}

/* ---------- the three artefacts ----------
   The token is the single point of coupling between them: the CSS block
   consumes exactly `--content-primary` and the `## Tokens` list declares
   exactly `--content-primary`, which is what build.mjs's cross-check demands
   in both directions. Add a declaration, add the token to the list. */
const TOKEN = "--content-primary";

/* `since` names the BUILD-LOG.md phase a component first shipped in, and
   build.mjs only accepts a phase it knows. If a later phase exists by the time
   you read this, the gate will say so by name — that is the intended failure. */
const SINCE = "phase-3";

const specText = `---
{
  "id": "${id}",
  "status": "experimental",
  "since": "${SINCE}",
  "a11y": "TODO(scaffold) — one line: what a screen reader or a keyboard gets here, or why it needs nothing."
}
---

# ${title}

TODO(scaffold) — one paragraph: what this is, and what it is NOT (the sibling
component it would otherwise be confused with).

## Pattern

This is not an example, it is THE pattern. Copy it verbatim.

\`\`\`html
<div class="${id}">TODO(scaffold)</div>
\`\`\`

## Tokens

\`${TOKEN}\`

## AI notes

- TODO(scaffold) — when to reach for this, and when not to.
`;

const storyText = `export default { title: "Components/${title}" };

export const Default = {
  render: () => \`<div class="${id}">TODO(scaffold)</div>\`,
};
`;

/* The fourth artefact. Appearance as data, in the smallest shape the schema
   accepts: an id, a banner, a root and one bound declaration. Everything else —
   variants, sizes, parts, states, positions, conditions — is OPTIONAL and is
   added by the block that needs it, which is the discipline the whole format is
   built on. components/definition.schema.json documents every construct and
   names the block that forced it. */
const definition = {
  $doc: `TODO(scaffold) — this component's appearance as prose: the decisions the declarations record. Not published; contract-diff.mjs snapshots the resolved declarations and no prose.`,
  $schema: "../definition.schema.json",
  id,
  block: {
    title,
    note: [
      "TODO(scaffold) — why this block exists: the decision it records, not what",
      "the declarations do. Anything obvious from the CSS does not belong here.",
    ],
  },
  root: `.${id}`,
  base: { declarations: [{ set: { color: { token: TOKEN.replace(/^--/, "") } } }] },
};
const definitionText = JSON.stringify(definition, null, 2) + "\n";

/* An EMPTY region: the markers, and the emitter fills the body below. */
const cssBlock = `${openMarker(id)}\n${closeMarker(id)}\n\n`;

/* Reduced motion stays last: it is a block of overrides, and the cascade is
   the only thing that makes them overrides. */
const ANCHOR = "/* ============ Reduced motion ============ @component none */";
/* Back up over the census marker above the banner. Since R4 every block carries
   one — `authored:none — unnamed-condition` here — and inserting between a
   marker and the banner it introduces would orphan both: the new block would
   wear reduced motion's reason and reduced motion would wear none. */
const bannerAt = css.indexOf(ANCHOR);
const anchorAt = (() => {
  if (bannerAt === -1) return -1;
  const lineStart = css.lastIndexOf("\n", css.lastIndexOf("\n", bannerAt - 1) - 1) + 1;
  const above = css.slice(lineStart, bannerAt).trim();
  return /^\/\* ---- (authored|generated):/.test(above) ? lineStart : bannerAt;
})();
const nextCss = anchorAt === -1 ? css.replace(/\s*$/, "\n\n") + cssBlock : css.slice(0, anchorAt) + cssBlock + css.slice(anchorAt);

/* ---------- the three registrations ----------
   Each is one literal line in a mechanical list, and each is anchored on text
   that must exist: a missing anchor DIES rather than writing a file that has
   quietly stopped being registered. A scaffold that half-registers a component
   is worse than one that refuses. */
const registrations = [];
const register = (rel, transform) => {
  const path = join(root, rel);
  const before = readFileSync(path, "utf8");
  const after = transform(before);
  if (after === null) {
    die(
      `could not find the anchor for \`${id}\` in ${rel}. That file's shape has changed, and this scaffold\n` +
        `  would have written a component that nothing renders, publishes or compares. Fix the anchor in\n` +
        `  scripts/new-component.mjs — nothing has been written.`
    );
  }
  registrations.push({ rel, path, contents: after });
};

register("design-system/scripts/emit-css.mjs", (src) => {
  const m = /export const PILOT = \[([^\]]*)\];/.exec(src);
  if (!m) return null;
  return src.replace(m[0], `export const PILOT = [${m[1]}, "${id}"];`);
});

register("design-system/scripts/build.mjs", (src) => {
  const open = src.indexOf("const packaged = [");
  if (open === -1) return null;
  const close = src.indexOf("\n];", open);
  if (close === -1) return null;
  return src.slice(0, close) + `\n  ["dist/react/${id}.tsx", reactSource("${id}")],` + src.slice(close);
});

register("design-system/package.json", (src) => {
  const m = /(\n    "\.\/react\/[a-z0-9-]+": "\.\/dist\/react\/[a-z0-9-]+\.tsx")(\n  \},)/.exec(src);
  if (!m) return null;
  return src.replace(m[0], `${m[1]},\n    "./react/${id}": "./dist/react/${id}.tsx"${m[2]}`);
});

const plan = [
  { path: `design-system/components/${id}/definition.json`, op: "create", contents: definitionText },
  { path: `design-system/components/${id}/spec.md`, op: "create", contents: specText },
  { path: `design-system/stories/${id}.stories.js`, op: "create", contents: storyText },
  {
    path: "design-system/css/components.css",
    op: anchorAt === -1 ? "append" : "insert-before-reduced-motion",
    contents: cssBlock,
  },
];

/* The registrations are reported SEPARATELY from the artefacts, and the split is
   the one test/scaffold.test.js reads: `files` is what this scaffold creates and
   is asserted line by line, `registers` is what it edits in three lists that
   already exist. Folding the second into the first would make "the artefacts a
   component is" depend on how many lists happen to need a line today. */
const registerPlan = registrations.map(({ rel }) => ({ path: rel, op: "register", names: id }));

if (JSON_OUT) {
  console.log(JSON.stringify({ id, title, token: TOKEN, files: plan, registers: registerPlan }, null, 2));
  process.exit(0);
}

if (DRY) {
  console.log(`— dry run, nothing written —\n`);
  for (const f of plan) console.log(`${f.op} ${f.path}\n${"-".repeat(60)}\n${f.contents}`);
  for (const r of registerPlan) console.log(`${r.op} ${r.path}  (one line naming \`${r.names}\`)`);
  process.exit(0);
}

/* ---------- write ---------- */
mkdirSync(compDir, { recursive: true });
writeFileSync(join(compDir, "definition.json"), definitionText);
writeFileSync(join(compDir, "spec.md"), specText);
writeFileSync(storyPath, storyText);
writeFileSync(cssPath, nextCss);
for (const r of registrations) writeFileSync(r.path, r.contents);

/* Fill the empty region from the definition, by running the emitter rather than
   importing it — see the note at the top. A failure here leaves the region empty
   and the assembly check red, which is the loud outcome rather than a quiet one. */
execFileSync("node", ["design-system/scripts/emit-css.mjs"], { cwd: root, stdio: "inherit" });

for (const f of [...plan, ...registerPlan]) console.log(`✓ ${f.op.padEnd(30)} ${f.path}`);

/* ---------- what the gates will say next ----------
   The count is a claim the site makes about itself, asserted by build.mjs in
   four files. Two are generated and `npm run build` fixes them. Two are prose,
   and are printed here with their line numbers rather than rewritten. */
const count = readdirSync(join(ds, "components"), { withFileTypes: true }).filter((d) => d.isDirectory()).length;
const was = count - 1;

const advertised = [
  ["README.md", `${was} components`],
  ["design-system/README.md", `(${was})`],
];
const hits = [];
for (const [rel, needle] of advertised) {
  const path = join(root, rel);
  if (!existsSync(path)) continue;
  readFileSync(path, "utf8")
    .split("\n")
    .forEach((line, i) => {
      if (line.includes(needle)) hits.push(`${rel}:${i + 1}  ${line.trim()}`);
    });
}

const placeholders = plan.reduce((n, f) => n + (f.contents.match(/TODO\(scaffold\)/g) ?? []).length, 0);

console.log(
  `\nCoverage, the census, the \`@component\` marker and the spec↔CSS contract are already\n` +
    `satisfied, and so are the three registrations — the block is GENERATED from its definition,\n` +
    `because a one-declaration block has no honest authored reason to give the census.\n` +
    `Four things are not, and none of them is a machine's to do:\n` +
    `\n  1. The component count moved ${was} → ${count}, and build.mjs --check asserts it in four files.\n` +
    `     Two are GENERATED — \`npm run build\` rewrites cv.html and work/portfolio-system.html.\n` +
    `     Two are prose somebody wrote, so change ${was} to ${count} by hand:\n` +
    (hits.length ? hits.map((h) => `       ${h}`).join("\n") : `       README.md and design-system/README.md`) +
    `\n\n  2. ${placeholders} \`TODO(scaffold)\` placeholders. test/placeholders.test.js fails while any survive:\n` +
    `       design-system/components/${id}/definition.json  (the $doc and the banner note)\n` +
    `       design-system/components/${id}/spec.md          (a11y line, description, AI notes)\n` +
    `       design-system/stories/${id}.stories.js\n` +
    `\n  3. The subpath count. design-system/package.json's \`//exports\` sentence says how many\n` +
    `     there are, and there is now one more. The version is the same kind of claim: a new\n` +
    `     export subpath and new definition rules are ADDITIVE, so\n` +
    `       node design-system/scripts/contract-diff.mjs --release   (a MINOR bump)\n` +
    `\n  4. The component itself. One class, one token — grow it from there, in the definition\n` +
    `     rather than in the CSS: css/components.css is generated for this id now, and editing\n` +
    `     inside the region fails the assembly check by design.\n` +
    `\nThen:  npm run build   &&   npm run check\n`
);
