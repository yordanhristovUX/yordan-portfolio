/* ============================================================
   The five generated regions of /evals, rendered from evals/dist/page.json.

   On the vanilla site these are HTML written between `<!-- content:evals-… -->`
   markers by `evals/run.mjs`. Here they are rendered from the STRUCTURED fields
   of the same run's page.json — which is the point of the second surface: if
   this file rendered `region.html` it would be copying the first renderer's
   output, and the structured serialization nothing would ever check. The proof
   that the two agree is a byte-diff of this page's export against evals.html's
   regions, and it is the phase's exit criterion rather than a claim here.

   EVERY STRING FROM THE ARTEFACT GOES THROUGH dangerouslySetInnerHTML. That is
   not a shortcut around escaping, it is the file's contract (see src/lib/
   evals.ts): the strings are already escaped exactly as evals.html carries
   them, so React's own escaping would double it and print `p &lt; 0.0001`
   literally. The source is a committed artefact generated by a script in this
   repo and covered by `node evals/run.mjs --check`; nothing here comes from a
   request or a user.

   WHY A FEW ELEMENTS ARE COMPOSED AS MARKUP STRINGS rather than JSX. A `<dt>`
   whose text is an HTML string from the artefact and whose sibling is a chip
   cannot be written in JSX without an extra wrapper element around one of them,
   and an extra element is a byte difference in a page whose exit gate is a byte
   diff. So `dt` and `.fact__num` build their inner HTML — from DS class names
   only, and from strings the artefact already escaped.

   NO CLASS NAME HERE IS NEW: `facts`, `fact`, `fact__num/__title/__label`,
   `tools`, `tools__row`, `chips`, `chip`, `chip--solid` are the design
   system's, and `ev-note` / `ev-prose` are css/evals.css's, synced in.

   AND NONE OF THEM WAS SWAPPED TO THE GENERATED <Chip> IN R2b, for the reason
   in the first paragraph: the exit gate for this page is a BYTE DIFF against
   evals.html's regions. A `<Chip>` emits fifteen utility classes where the
   artefact emits `class="chip"`, so swapping here would fail the one check that
   proves the two renderers agree. One of these chips is not even JSX — the
   counterfactual marker below is composed into an HTML string — which is the
   same fact from the other side: this file reproduces an artefact's markup, so
   the artefact's generator is where a class name changes first. These stay on
   components.css until it does.

   R5 CUT THE WHOLE APP OVER TO THE REACT TIER AND DELIBERATELY LEFT THIS FILE
   BEHIND, on exactly that argument. The cutover's claim is that every
   APP-AUTHORED element consumes the generated components; this file authors
   nothing — it renders an artefact, and an artefact's markup belongs to its
   generator. `components.css` is still imported by src/app/layout.tsx and is
   what styles every class named above, which is not a leftover either: six
   design-system blocks have no React form and never will, so the stylesheet
   was never going away. Two things follow and neither is optional. The class
   names here may only change when `evals/run.mjs` changes them, upstream; and
   the byte diff stays the gate for this page while the rest of the app is
   measured by computed style instead.

   The page AROUND these regions — its `.sec` bands and `.sec__head`s in
   src/app/evals/page.tsx — IS app-authored and did swap. The boundary is the
   region, exactly where evals.html draws it.
   ============================================================ */
import type {
  ArmsRegion,
  CategoriesRegion,
  DefinitionsRegion,
  EvalsMetric,
  FactsRegion,
  Html,
  ProseRegion,
} from "@/lib/evals";

/** `<span class="chip">` — solid marks the one leader in its group. */
function Chip({ html, solid }: { html: Html; solid?: boolean }) {
  return (
    <span className={solid ? "chip chip--solid" : "chip"} dangerouslySetInnerHTML={{ __html: html }} />
  );
}

/* A metric chip reads "hit@3 91.8% ±8.0". The half-width is omitted rather
   than printed as a bare ± when the artefact has none for that column. */
const metricChipHtml = (m: EvalsMetric): Html => `${m.label} ${m.value}${m.half ? ` ${m.half}` : ""}`;

function MetricChip({ metric }: { metric: EvalsMetric }) {
  return <Chip html={metricChipHtml(metric)} solid={metric.best} />;
}

/* One paragraph, authored as lines so it stays readable in the generator. The
   join is a space: these are line breaks in a source file, not sentences. */
function Note({ lines }: { lines: Html[] }) {
  return <p className="ev-note" dangerouslySetInnerHTML={{ __html: lines.join(" ") }} />;
}

/** A definition row's term, with the counterfactual chip when it carries one. */
function Term({ html, counterfactual }: { html: Html; counterfactual?: boolean }) {
  return (
    <dt
      dangerouslySetInnerHTML={{
        __html: counterfactual ? `${html} <span class="chip">counterfactual</span>` : html,
      }}
    />
  );
}

/* ---------- evals-summary · the four facts ---------- */
export function SummaryFacts({ region }: { region: FactsRegion }) {
  return (
    <div className="facts">
      {region.facts.map((f) => (
        <div className="fact" key={f.title}>
          <span
            className="fact__num"
            dangerouslySetInnerHTML={{ __html: `${f.value}${f.unit ? `<small>${f.unit}</small>` : ""}` }}
          />
          <span className="fact__title" dangerouslySetInnerHTML={{ __html: f.title }} />
          <span className="fact__label" dangerouslySetInnerHTML={{ __html: f.label }} />
        </div>
      ))}
    </div>
  );
}

/* ---------- evals-table · arms, paired tests, separability ----------
   Three definition lists and three notes, in that order. `skipped` is null on
   a run that measured every arm and is a row that SAYS SO on one that did not
   — never a number borrowed from somewhere else. */
export function ArmsTable({ region }: { region: ArmsRegion }) {
  return (
    <>
      <dl className="tools">
        {region.arms.map((a) => (
          <div className="tools__row" key={a.arm}>
            <Term html={a.arm} counterfactual={a.counterfactual} />
            <dd className="chips">
              {a.metrics.map((m) => (
                <MetricChip key={m.key} metric={m} />
              ))}
            </dd>
          </div>
        ))}
        {region.skipped ? (
          <div className="tools__row">
            <Term html={region.skipped.arm} />
            <dd dangerouslySetInnerHTML={{ __html: region.skipped.text }} />
          </div>
        ) : null}
      </dl>
      <Note lines={region.armsNote} />

      {region.paired.length ? (
        <>
          <dl className="tools">
            {region.paired.map((s) => (
              <div className="tools__row" key={`${s.a} vs ${s.b}`}>
                <Term html={`${s.a} vs ${s.b}`} />
                <dd className="chips">
                  <Chip html={s.counts} />
                  <Chip html={s.p} solid={s.significant} />
                  <Chip html={s.verdict} />
                  <Chip html={s.note} />
                </dd>
              </div>
            ))}
          </dl>
          <Note lines={region.pairedNote} />
        </>
      ) : null}

      <dl className="tools">
        {region.separability.map((s) => (
          <div className="tools__row" key={s.arm}>
            <Term html={`separability · ${s.arm}`} />
            <dd className="chips">
              <Chip html={`all pairs ${s.allPairs}`} />
              <Chip html={`${s.emptyDriven} won by returning nothing`} />
              <Chip html={`${s.tied} tied empty`} />
              <Chip html={`${s.lostByRefusingAnAnswer} lost by refusing an answerable one`} />
              <Chip html={s.scored === null ? "no scored pairs" : `scored pairs only ${s.scored}`} />
            </dd>
          </div>
        ))}
      </dl>
      <Note lines={region.separabilityNote} />
    </>
  );
}

/* ---------- evals-categories · hit@3 (or abstention) per question class ---------- */
export function CategoryTable({ region }: { region: CategoriesRegion }) {
  return (
    <>
      <dl className="tools">
        {region.categories.map((c) => (
          <div className="tools__row" key={c.category}>
            <Term html={c.category} />
            <dd className="chips">
              <Chip html={c.nLabel} />
              <Chip html={c.metric} />
              {c.arms.map((a) => (
                <MetricChip key={a.key} metric={a} />
              ))}
            </dd>
          </div>
        ))}
      </dl>
      <Note lines={region.note} />
    </>
  );
}

/* ---------- evals-reading · the owner's prose ----------
   Each paragraph is a complete `<p>…</p>` with its own <strong>, <em>, <code>
   and curly quotes. It is shipped verbatim: never re-worded, never re-flowed
   around a number. `.ev-prose` is the wrapper the vanilla page puts around the
   region, so it carries the markup itself rather than adding an element. */
export function ReadingProse({ region }: { region: ProseRegion }) {
  return <div className="ev-prose" dangerouslySetInnerHTML={{ __html: region.paragraphs.join("") }} />;
}

/* ---------- evals-corpus · what the index is made of ---------- */
export function CorpusRows({ region }: { region: DefinitionsRegion }) {
  return (
    <dl className="tools">
      {region.rows.map((r) => (
        <div className="tools__row" key={r.term}>
          <Term html={r.term} />
          <dd dangerouslySetInnerHTML={{ __html: r.definition }} />
        </div>
      ))}
    </dl>
  );
}
